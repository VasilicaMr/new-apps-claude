import Foundation

final class ScoringEngineFactory: Sendable {
    func engine(for sport: SportType, variant: String?) -> any ScoringEngine {
        switch sport {
        case .darts:            return DartsScoringEngine(variant: variant ?? "501")
        case .archery:          return ArcheryScoringEngine()
        case .sportShooting:    return SportShootingScoringEngine()
        case .axeThrowing:      return AxeThrowingScoringEngine()
        case .knifeThrowing:    return ZoneBasedScoringEngine(sport: .knifeThrowing)
        case .slingshot:        return ZoneBasedScoringEngine(sport: .slingshot)
        case .blowgun:          return ZoneBasedScoringEngine(sport: .blowgun)
        case .pool:             return PoolScoringEngine(variant: variant ?? "8-Ball")
        case .snooker:          return SnookerScoringEngine()
        case .caroms:           return CaromScoringEngine(variant: "Straight")
        case .cushionCaroms:    return CaromScoringEngine(variant: "3-Cushion")
        case .bowlingTenPin:    return TenPinBowlingScoringEngine()
        case .bowlingNinePin:   return NinePinScoringEngine()
        case .bowlingCandlepin: return CandlepinScoringEngine()
        case .bowlingDuckpin:   return DuckpinScoringEngine()
        case .bocce:            return BocceScoringEngine(sport: .bocce)
        case .petanque:         return BocceScoringEngine(sport: .petanque)
        case .boules:           return BocceScoringEngine(sport: .boules)
        case .lawnBowls:        return LawnBowlsScoringEngine()
        case .skittles:         return SkittlesScoringEngine()
        case .tableTennis:      return TableTennisScoringEngine(variant: variant)
        case .badminton:        return BadmintonScoringEngine()
        case .squash:           return SquashScoringEngine(variant: variant ?? "PAR")
        case .racquetball:      return RacquetballScoringEngine()
        case .tennis:           return TennisScoringEngine(variant: variant)
        case .padel:            return PadelScoringEngine()
        case .pickleball:       return PickleballScoringEngine()
        case .dominoes:         return DominoesScoringEngine(variant: variant ?? "Draw")
        case .mahjong:          return MahjongScoringEngine(variant: variant ?? "Chinese")
        case .cribbage:         return CribbageScoringEngine()
        case .pokerTournament:  return PokerTournamentEngine()
        case .chess:            return ChessScoringEngine()
        case .checkers:         return CheckersScoringEngine()
        case .go:               return GoScoringEngine(boardSize: variant ?? "19×19")
        case .backgammon:       return BackgammonScoringEngine()
        case .scrabble:         return ScrabbleScoringEngine()
        case .curling:          return CurlingScoringEngine()
        case .horseshoes:       return HorseshoesScoringEngine()
        case .cornhole:         return CornholeScoringEngine()
        case .ringToss:         return RingTossScoringEngine()
        case .discGolf:         return DiscGolfScoringEngine()
        case .kubb:             return KubbScoringEngine()
        case .croquet:          return CroquetScoringEngine(variant: variant ?? "Association")
        case .shuffleboard:     return ShuffleboardScoringEngine()
        case .airHockey:        return AirHockeyScoringEngine()
        case .foosball:         return FoosballScoringEngine()
        case .pinball:          return PinballScoringEngine()
        case .armWrestling:     return ArmWrestlingScoringEngine()
        }
    }
}
